import HttpClient, { ApiResponse, mapData } from "../types";
import { PH_BASE_PATH, buildQuery } from "./types";
import type { PaymentStatus } from "./payment_status";

/** An enabled provider / method pair (from the payment integrator's plugins). */
export type PaymentGatewayMethod = {
  providerCode: string;
  providerName?: string;
  code: string;
  label: string;
  currencies: string[];
};

/** How to send the browser to the provider's hosted checkout. */
export type PaymentRedirect = {
  transactionId: string;
  status: GatewayTransactionStatus;
  /** `GET` → navigate to `url`; `POST` → submit `form` to `url`. */
  method: "GET" | "POST";
  url?: string;
  form?: Record<string, unknown>;
};

export type GatewayTransactionStatus =
  | "DRAFT"
  | "PENDING"
  | "PROCESSING"
  | "COMPLETED"
  | "FAILED"
  | "CANCELLED"
  | "EXPIRED"
  | "REFUNDED";

export type GatewayTransaction = {
  id: string;
  status: GatewayTransactionStatus;
  /** paid / pending / failed, for the shared status badge. */
  statusKey: PaymentStatus;
  statusMessage?: string;
  provider?: string;
  paymentMethod?: string;
  amount: number;
  currency?: string;
  contractId?: string;
  contractCode?: string;
  initiatedAt?: string;
  completedAt?: string;
};

export type PayContractInput = {
  contractId: string;
  providerCode: string;
  paymentMethodCode: string;
  /** Where the provider sends the browser after checkout (portal return page). */
  returnUrl?: string;
  /** Repeat the same key to retry safely; generated by the backend when omitted. */
  idempotencyKey?: string;
};

const TERMINAL_FAILED = new Set(["FAILED", "CANCELLED", "EXPIRED"]);

export function classifyGatewayStatus(status: string | undefined): PaymentStatus {
  const s = String(status ?? "").toUpperCase();
  if (s === "COMPLETED") return "paid";
  if (TERMINAL_FAILED.has(s)) return "failed";
  return "pending";
}

type Rec = Record<string, unknown>;
const rec = (v: unknown): Rec => (v && typeof v === "object" ? (v as Rec) : {});
const str = (v: unknown): string | undefined =>
  typeof v === "string" && v.trim() ? v : undefined;

export function parseGatewayTransaction(raw: unknown): GatewayTransaction {
  const r = rec(raw);
  const status = (str(r.status) ?? "PENDING").toUpperCase() as GatewayTransactionStatus;
  return {
    id: String(r.id ?? ""),
    status,
    statusKey: classifyGatewayStatus(status),
    statusMessage: str(r.statusMessage),
    provider: str(r.provider),
    paymentMethod: str(r.paymentMethod),
    amount: Number(r.amount ?? 0),
    currency: str(r.currency),
    contractId: str(r.contractId),
    contractCode: str(r.contractCode),
    initiatedAt: str(r.initiatedAt),
    completedAt: str(r.completedAt),
  };
}

/** `{ success, data }` envelope of the payment-gateway endpoints. */
function envelope(raw: unknown): unknown {
  return rec(raw).data;
}

function parseMethod(raw: unknown): PaymentGatewayMethod {
  const r = rec(raw);
  const currencies = r.supported_currencies ?? r.currencies;
  return {
    providerCode: String(r.provider_code ?? r.providerCode ?? ""),
    providerName: str(r.provider_name ?? r.providerName),
    code: String(r.code ?? ""),
    label: str(r.label) ?? String(r.code ?? ""),
    currencies: Array.isArray(currencies) ? currencies.map(String) : [],
  };
}

export function parsePaymentRedirect(raw: unknown): PaymentRedirect {
  const r = rec(envelope(raw));
  const form = rec(r.redirect_form);
  return {
    transactionId: String(r.transaction_id ?? ""),
    status: (str(r.status) ?? "PENDING").toUpperCase() as GatewayTransactionStatus,
    method: String(r.redirect_method ?? "GET").toUpperCase() === "POST" ? "POST" : "GET",
    url: str(r.redirect_url) ?? str(r.payment_url),
    form: Object.keys(form).length ? form : undefined,
  };
}

/**
 * Online contract payments (`/policy-holder-dev-api/payment-gateway/`). The backend
 * resolves the contract's invoice, amount and currency; the client sends only the
 * contract and the chosen provider / method.
 */
class FormalSectorPaymentGatewayClient {
  constructor(private readonly httpClient: HttpClient) {}

  async methods(): Promise<ApiResponse<PaymentGatewayMethod[]>> {
    const response = await this.httpClient.get<unknown>(`${PH_BASE_PATH}/payment-gateway/methods/`);
    return mapData(response, (raw) => {
      const list = envelope(raw);
      return Array.isArray(list) ? list.map(parseMethod) : [];
    });
  }

  async payContract(input: PayContractInput): Promise<ApiResponse<PaymentRedirect>> {
    if (!input.contractId?.trim()) return ApiResponse.fail("400", "Contract is required");
    if (!input.providerCode?.trim() || !input.paymentMethodCode?.trim()) {
      return ApiResponse.fail("400", "Choose a payment method");
    }
    const response = await this.httpClient.post<unknown>(`${PH_BASE_PATH}/payment-gateway/pay/`, {
      contract_id: input.contractId,
      provider_code: input.providerCode,
      payment_method_code: input.paymentMethodCode,
      return_url: input.returnUrl,
      idempotency_key: input.idempotencyKey,
    });
    return mapData(response, parsePaymentRedirect);
  }

  /** Current status; the backend re-verifies pending payments with the provider. */
  async transaction(id: string): Promise<ApiResponse<GatewayTransaction>> {
    const response = await this.httpClient.get<unknown>(
      `${PH_BASE_PATH}/payment-gateway/${encodeURIComponent(id)}/`
    );
    return mapData(response, (raw) => parseGatewayTransaction(envelope(raw)));
  }

  async transactions(
    pageOffset?: number,
    count?: number
  ): Promise<ApiResponse<{ total: number; items: GatewayTransaction[] }>> {
    const query = buildQuery({ "page-offset": pageOffset, _count: count });
    const response = await this.httpClient.get<unknown>(`${PH_BASE_PATH}/payment-gateway/${query}`);
    return mapData(response, (raw) => {
      const data = rec(envelope(raw));
      const items = Array.isArray(data.items) ? data.items.map(parseGatewayTransaction) : [];
      return { total: Number(data.total ?? items.length), items };
    });
  }

  /** Every transaction (paged internally; capped at `maxPages` × `pageSize`). */
  async allTransactions(
    pageSize = 50,
    maxPages = 50
  ): Promise<ApiResponse<{ items: GatewayTransaction[]; total: number; truncated: boolean }>> {
    const items: GatewayTransaction[] = [];
    let total = 0;
    for (let page = 1; page <= maxPages; page++) {
      const resp = await this.transactions(page, pageSize);
      if (!resp.success || !resp.data) {
        return ApiResponse.fail(resp.statusCode, resp.message, resp.errorDetails);
      }
      total = resp.data.total;
      items.push(...resp.data.items);
      if (resp.data.items.length === 0 || items.length >= total) {
        return ApiResponse.ok({ items, total, truncated: false });
      }
    }
    return ApiResponse.ok({ items, total, truncated: true });
  }
}

export default FormalSectorPaymentGatewayClient;
